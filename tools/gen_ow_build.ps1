# Generates ow/rules.mk and the wlink response files for the OpenWatcom build.
# Run from the repository root:  powershell -File tools/gen_ow_build.ps1
$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
Set-Location $root
New-Item -ItemType Directory -Force ow | Out-Null

$project = Get-ChildItem src -Recurse -Filter *.c | Sort-Object FullName
$bearssl = Get-ChildItem third_party\bearssl\src -Recurse -Filter *.c | Sort-Object FullName

function Rel($p) { (Resolve-Path -Relative $p).TrimStart('.', '\', '/') -replace '/', '\' }

# wmake has no dependency discovery of its own.  Without an explicit header
# list, editing src/core/config.h did not rebuild the modules that include it,
# which leaves objects compiled against different struct layouts in the same
# executable.  Over-building costs a few seconds; a stale build costs an
# afternoon of chasing random crashes.
$headers = @()
$headers += Get-ChildItem src -Recurse -Filter *.h |
    Sort-Object FullName | ForEach-Object { Rel $_.FullName }
$headers += 'third_party\cjson\cJSON.h'
$headerDeps = ($headers -join ' ')

$rules = New-Object System.Collections.Generic.List[string]
$projectObjs = New-Object System.Collections.Generic.List[string]

$rules.Add('# Generated by tools/gen_ow_build.ps1 - do not edit by hand.')
$rules.Add('')
$rules.Add('PROJECT_CFLAGS = -c -bt=nt -bm -zq -za99 -ox -i=src -i=src\core -i=src\agent -i=src\net -i=src\gui -i=third_party\cjson -i=third_party\bearssl\inc -i=third_party\bearssl\src')
$rules.Add('BEARSSL_CFLAGS = -c -bt=nt -bm -zq -ox -i=third_party\bearssl\inc -i=third_party\bearssl\src')
$rules.Add('')

foreach ($f in $project) {
    $src = Rel $f.FullName
    $obj = 'build\ow\obj\' + $f.BaseName + '.obj'
    $projectObjs.Add($obj)
    # The recipe names $src explicitly instead of using wmake's $<: in
    # OpenWatcom wmake, $< expands to *all* prerequisites, so listing the
    # headers there would pass them to the compiler as extra source files.
    $rules.Add("$obj`: $src $headerDeps")
    $rules.Add("`t`$(CC) `$(PROJECT_CFLAGS) -fo=`$@ $src")
    $rules.Add('')
}

$cjson = 'build\ow\obj\cjson.obj'
$projectObjs.Add($cjson)
$rules.Add("$cjson`: third_party\cjson\cJSON.c third_party\cjson\cJSON.h")
$rules.Add("`t`$(CC) `$(PROJECT_CFLAGS) -DCJSON_HIDE_SYMBOLS -fo=`$@ third_party\cjson\cJSON.c")
$rules.Add('')

$bearsslObjs = New-Object System.Collections.Generic.List[string]
foreach ($f in $bearssl) {
    $src = Rel $f.FullName
    $obj = 'build\ow\obj\bearssl\' + $f.BaseName + '.obj'
    $bearsslObjs.Add($obj)
    $rules.Add("$obj`: $src")
    $rules.Add("`t`$(CC) `$(BEARSSL_CFLAGS) -fo=`$@ $src")
    $rules.Add('')
}

$cliObjs = New-Object System.Collections.Generic.List[string]
$guiObjs = New-Object System.Collections.Generic.List[string]
$probeObjs = New-Object System.Collections.Generic.List[string]
$sharedObjs = New-Object System.Collections.Generic.List[string]

foreach ($o in $projectObjs) {
    $base = [System.IO.Path]::GetFileName($o)
    if ($base -eq 'main.obj') {
        $cliObjs.Add($o)
    } elseif ($base -eq 'main_gui.obj') {
        $guiObjs.Add($o)
    } elseif ($base -eq 'tlsprobe.obj') {
        $probeObjs.Add($o)
    } else {
        $sharedObjs.Add($o)
    }
}
foreach ($o in $bearsslObjs) {
    $sharedObjs.Add($o)
}
foreach ($o in $sharedObjs) {
    $cliObjs.Add($o)
    $guiObjs.Add($o)
    $probeObjs.Add($o)
}

$rules.Add('OBJS =')
foreach ($o in $cliObjs) { $rules.Add("OBJS += $o") }
$rules.Add('')
$rules.Add('GUI_OBJS =')
foreach ($o in $guiObjs) { $rules.Add("GUI_OBJS += $o") }
$rules.Add('')
$rules.Add('PROBE_OBJS =')
foreach ($o in $probeObjs) { $rules.Add("PROBE_OBJS += $o") }
$rules.Add('')

Set-Content -Path 'ow\rules.mk' -Value $rules -Encoding ascii

function Write-LinkFile($path, $name, $subsystem, $list, $resource) {
    $link = New-Object System.Collections.Generic.List[string]
    $link.Add("system $subsystem")
    $link.Add("name $name")
    $link.Add('option map=' + ($name -replace '\.exe$', '.map'))
    # Windows 95/98/ME compatibility.  Win9x's PE loader is much less
    # forgiving than the NT loader, so pin the image at the standard user
    # base, strip the relocation table (the image is fixed-base anyway) and
    # keep the image/subsystem version at 4.0.  A 256 KB stack keeps the
    # BearSSL client contexts comfortable during the TLS handshake.
    $link.Add('option offset=0x400000')
    $link.Add('option norelocs')
    $link.Add('option version=4.0')
    $link.Add('option stack=262144')
    if ($resource) {
        $link.Add('option resource=' + $resource)
    }
    foreach ($o in $list) { $link.Add('file ' + ($o -replace '\\', '/')) }
    $link.Add('library ws2_32.lib')
    $link.Add('library advapi32.lib')
    $link.Add('library user32.lib')
    $link.Add('library gdi32.lib')
    $link.Add('library comdlg32.lib')
    if ($subsystem -eq 'nt_win') {
        # Status bar common control and ShellExecuteA for "Open workspace".
        $link.Add('library comctl32.lib')
        $link.Add('library shell32.lib')
    }
    Set-Content -Path $path -Value $link -Encoding ascii
}

Write-LinkFile 'ow\link.rsp' 'build/ow/a98.exe' 'nt' $cliObjs $null
Write-LinkFile 'ow\link_gui.rsp' 'build/ow/agent98.exe' 'nt_win' $guiObjs 'build/ow/gui.res'
Write-LinkFile 'ow\link_tlsprobe.rsp' 'build/ow/tlsprobe.exe' 'nt' $probeObjs $null

Write-Host ("Generated ow/rules.mk with {0} project objects." -f $projectObjs.Count)
